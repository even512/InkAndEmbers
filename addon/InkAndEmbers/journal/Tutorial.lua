local function isSecret(v)
  return type(issecretvalue) == "function" and issecretvalue(v) == true
end

local function inCombat()
  if type(InCombatLockdown) ~= "function" then return false end
  local ok, v = pcall(InCombatLockdown)
  return ok and not isSecret(v) and v == true
end

local function print_(msg)
  if ns.Core and type(ns.Core.print) == "function" then ns.Core.print(msg) end
end

local function W() return Journal.Widgets end
local function D() local w = W() return w and w.Diary end
local function Theme() return Journal.Theme or { C = {}, TEX = {}, FONT = {} } end

local function play(name)
  local S = Journal.Sound
  if S and type(S.play) == "function" then pcall(S.play, name) end
end

local function uiTable(create)
  local db = EveNChronicleDB
  if type(db) ~= "table" then return nil end
  if type(db.ui) ~= "table" then
    if not create then return nil end
    db.ui = {}
  end
  return db.ui
end

function Tutorial.seen()
  local ui = uiTable(false)
  local v = ui and ui.tutorialSeen
  return type(v) == "number" and not isSecret(v) and v >= Tutorial.VERSION
end

function Tutorial.setSeen(on)
  local ui = uiTable(true)
  if not ui then return false end
  ui.tutorialSeen = on and Tutorial.VERSION or nil
  return true
end

function Tutorial.texture(atlas)
  local lang = (ns.Locale and ns.Locale.active == "enUS") and "enUS" or "deDE"
  return (Theme().MEDIA or "Interface\\AddOns\\InkAndEmbers\\Media\\") .. "Tutorial_" .. lang .. "_" .. (tonumber(atlas) or 1)
end

-- Texture coordinates of a tile ({ x, y, w, h } in atlas pixels), inset by half a texel
function Tutorial.tileCoords(tile)
  local n = Tutorial.ATLAS.size
  local eu, ev = 0.5 / n, 0.5 / n
  return tile.x / n + eu, (tile.x + tile.w) / n - eu, tile.y / n + ev, (tile.y + tile.h) / n - ev
end

local function setText(fs, text)
  local w = W()
  if w and w.setText then w.setText(fs, text) else fs:SetText(type(text) == "string" and text or "") end
end

local function font(parent, kind, size, color, layer)
  local d = D()
  if d and d.font then return d.font(parent, kind, size, color, layer) end
  local fs = parent:CreateFontString(nil, layer or "OVERLAY")
  local Th = Theme()
  pcall(fs.SetFont, fs, (Th.FONT and (Th.FONT[kind] or Th.FONT.text)) or "Fonts\\FRIZQT__.TTF", size or 12, "")
  return fs
end

local function color(name, a)
  local w = W()
  if w and w.color then return w.color(name, a) end
  return 0.17, 0.13, 0.09, a or 1
end

local function textButton(parent, size, onClick)
  local b = CreateFrame("Button", nil, parent)
  b.text = font(b, "text", size, "sepia")
  b.text:SetPoint("CENTER", b, "CENTER", 0, 0)
  b.text:SetWordWrap(false)
  b:SetHeight(size + 10)
  local function paint(self)
    self.text:SetTextColor(color(self.hover and "red" or "sepia"))
  end
  b:SetScript("OnEnter", function(self) self.hover = true paint(self) end)
  b:SetScript("OnLeave", function(self) self.hover = false paint(self) end)
  b:SetScript("OnClick", function(self) if onClick then onClick(self) end end)
  function b:SetLabel(t)
    setText(self.text, t)
    local w = self.text.GetStringWidth and self.text:GetStringWidth() or 0
    if type(w) ~= "number" or w <= 0 then w = #(t or "") * size * 0.5 end
    self:SetWidth(floor(w + 12 + 0.5))
  end
  paint(b)
  return b
end

local function build()
  if state.frame then return state.frame end
  local Th = Theme()
  local Fr = Journal.Frame
  local f = CreateFrame("Frame", Tutorial.NAME, UIParent)
  f:SetSize(Tutorial.W, Tutorial.H)
  f:SetPoint("CENTER", UIParent, "CENTER", 0, 30)
  f:SetFrameStrata("FULLSCREEN_DIALOG")
  f:SetToplevel(true)
  f:SetClampedToScreen(true)
  f:EnableMouse(true)
  f:SetMovable(true)
  if f.SetDontSavePosition then f:SetDontSavePosition(true) end
  f:RegisterForDrag("LeftButton")
  f:SetScript("OnDragStart", function(self) self:StartMoving() end)
  f:SetScript("OnDragStop", function(self) self:StopMovingOrSizing() end)
  f:Hide()
  state.frame = f

  local pieces = (Fr and type(Fr.bookPieces) == "function") and Fr.bookPieces(Tutorial.W, Tutorial.H, Tutorial.RIM) or {}
  for _, p in ipairs(pieces) do
    local t = f:CreateTexture(nil, "BACKGROUND", nil, -8)
    t:SetTexture(Th.TEX.book)
    t:SetTexCoord(p.u0, p.u1, p.v0, p.v1)
    t:SetPoint("TOPLEFT", f, "TOPLEFT", p.x, -p.y)
    t:SetSize(p.w, p.h)
  end
  if #pieces == 0 then
    local bg = f:CreateTexture(nil, "BACKGROUND", nil, -8)
    bg:SetAllPoints(f)
    bg:SetColorTexture(0.30, 0.17, 0.10, 1)
  end

  local R = Tutorial.RIM
  local sw, sh = Tutorial.W - 2 * R, Tutorial.H - 2 * R
  local half = sw / 2
  local spread = CreateFrame("Frame", nil, f)
  spread:SetPoint("TOPLEFT", f, "TOPLEFT", R, -R)
  spread:SetSize(sw, sh)
  local pl, pr = "Interface\\AddOns\\InkAndEmbers\\Media\\Page_chronik_L", "Interface\\AddOns\\InkAndEmbers\\Media\\Page_chronik_R"
  if type(Th.paper) == "function" then pl, pr = Th.paper("chronik") end
  local left = CreateFrame("Frame", nil, spread)
  left:SetPoint("TOPLEFT", spread, "TOPLEFT", 0, 0)
  left:SetSize(half, sh)
  local right = CreateFrame("Frame", nil, spread)
  right:SetPoint("TOPLEFT", spread, "TOPLEFT", half, 0)
  right:SetSize(half, sh)
  local paperL = spread:CreateTexture(nil, "BACKGROUND")
  paperL:SetTexture(pl)
  paperL:SetPoint("TOPLEFT", spread, "TOPLEFT", 0, 14)
  paperL:SetSize(half, sh + 18)
  local paperR = spread:CreateTexture(nil, "BACKGROUND")
  paperR:SetTexture(pr)
  paperR:SetPoint("TOPLEFT", spread, "TOPLEFT", half, 14)
  paperR:SetSize(half, sh + 18)
  f.left, f.right = left, right

  local d = D()
  local upper = (d and d.upper) or string.upper
  f.headL = font(left, "label", 11, "sepia")
  f.headL:SetPoint("TOPLEFT", left, "TOPLEFT", 40, -32)
  f.headR = font(right, "label", 11, "sepia")
  f.headR:SetPoint("TOPRIGHT", right, "TOPRIGHT", -40, -32)
  f.headR:SetJustifyH("RIGHT")
  for _, side in ipairs({ left, right }) do
    local line = side:CreateTexture(nil, "ARTWORK")
    line:SetColorTexture(color("faint", 0.9))
    line:SetHeight(1)
    line:SetPoint("TOPLEFT", side, "TOPLEFT", 40, -48)
    line:SetPoint("TOPRIGHT", side, "TOPRIGHT", -40, -48)
  end
  f.upper = upper

  f.images = {}
  for slot = 1, 2 do
    local sh = {}
    sh.shadow = left:CreateTexture(nil, "BORDER")
    sh.shadow:SetColorTexture(0.17, 0.12, 0.07, 0.28)
    sh.line = left:CreateTexture(nil, "ARTWORK", nil, -1)
    sh.line:SetColorTexture(color("sepia", 0.55))
    sh.tex = left:CreateTexture(nil, "ARTWORK")
    if Th.TEX.diaryTape then
      sh.tape = left:CreateTexture(nil, "OVERLAY")
      sh.tape:SetTexture(Th.TEX.diaryTape)
      sh.tape:SetSize(96, 24)
      sh.tape:SetPoint("CENTER", sh.tex, "TOP", 0, 2)
      sh.tape:SetAlpha(0.92)
    end
    f.images[slot] = sh
  end
  f.image = f.images[1].tex
  f.portrait = left:CreateTexture(nil, "ARTWORK")
  f.portrait:SetSize(Tutorial.PORTRAIT, Tutorial.PORTRAIT)
  f.portrait:SetPoint("CENTER", left, "TOPLEFT", Tutorial.IMAGE.x + Tutorial.IMAGE.w / 2, -(Tutorial.IMAGE.top + Tutorial.IMAGE.bottom) / 2)
  f.portrait:Hide()

  f.dots = {}
  local n = #Tutorial.pages()
  local gap = 21
  local x0 = half / 2 - (n - 1) * gap / 2
  for i = 1, n do
    local b = CreateFrame("Button", nil, left)
    b:SetSize(18, 18)
    b:SetPoint("CENTER", left, "TOPLEFT", x0 + (i - 1) * gap, -(Tutorial.IMAGE.bottom + 26))
    local t = b:CreateTexture(nil, "ARTWORK")
    t:SetPoint("CENTER", b, "CENTER", 0, 0)
    t:SetTexture(Th.TEX.disc)
    b.mark = t
    b.index = i
    b:SetScript("OnClick", function(self) Tutorial.go(self.index) end)
    b:SetScript("OnEnter", function(self)
      self.hover = true
      Tutorial.paintDots()
      local w = W()
      if w and w.tip then w.tip(self, { T("dotTip", self.index) }) end
    end)
    b:SetScript("OnLeave", function(self)
      self.hover = false
      Tutorial.paintDots()
      local w = W()
      if w and w.hideTip then w.hideTip(self) end
    end)
    f.dots[i] = b
  end

  f.title = font(right, "hand", 30, "red")
  f.title:SetPoint("TOPLEFT", right, "TOPLEFT", 40, -Tutorial.TITLE_Y)
  f.title:SetWidth(Tutorial.TEXT_W)
  f.title:SetJustifyH("LEFT")
  f.title:SetWordWrap(false)
  if d and d.NewInkStroke then
    f.stroke = d.NewInkStroke(right, 170, "red", 0.8)
    f.stroke:SetPoint("TOPLEFT", right, "TOPLEFT", 40, -(Tutorial.TITLE_Y + 38))
  end
  f.body = font(right, "text", Tutorial.BODY_SIZES[1], "ink")
  f.body:SetPoint("TOPLEFT", right, "TOPLEFT", 40, -Tutorial.BODY_Y)
  f.body:SetWidth(Tutorial.TEXT_W)
  f.body:SetJustifyH("LEFT")
  f.body:SetJustifyV("TOP")
  if f.body.SetSpacing then f.body:SetSpacing(3) end

  if d and d.NewBack then
    f.back = d.NewBack(right, T.back, function() Tutorial.prev() end, { esc = false })
  else
    f.back = textButton(right, 14, function() Tutorial.prev() end)
    f.back:SetLabel(T.back)
  end
  f.back:SetPoint("BOTTOMLEFT", right, "BOTTOMLEFT", 36, 44)
  f.skip = textButton(right, 13, function() Tutorial.close() end)
  f.skip:SetPoint("BOTTOM", right, "BOTTOM", -24, 46)
  if d and d.NewSticker then
    f.next = d.NewSticker(right, T.next, function() Tutorial.next() end, { tilt = -2, size = 21 })
  else
    f.next = textButton(right, 16, function() Tutorial.next() end)
    f.next:SetLabel(T.next)
  end
  f.next:SetPoint("BOTTOMRIGHT", right, "BOTTOMRIGHT", -64, 40)

  f:SetScript("OnHide", function() Tutorial.onHidden() end)
  f:RegisterEvent("PLAYER_REGEN_DISABLED")
  f:SetScript("OnEvent", function(self, event)
    if event == "PLAYER_REGEN_DISABLED" then self:Hide() end
  end)

  if type(UISpecialFrames) == "table" then
    local present = false
    for _, name in ipairs(UISpecialFrames) do if name == Tutorial.NAME then present = true end end
    if not present then table.insert(UISpecialFrames, Tutorial.NAME) end
  end
  return f
end

function Tutorial.paintDots()
  local f = state.frame
  if not f then return end
  local Th = Theme()
  for i, b in ipairs(f.dots) do
    local cur = i == state.page
    local size = cur and 11 or (b.hover and 9 or 7)
    b.mark:SetSize(size, size)
    local c = cur and (Th.C and Th.C.red) or (b.hover and (Th.C and Th.C.red) or (Th.C and Th.C.sepia))
    c = c or { 0.42, 0.31, 0.2 }
    b.mark:SetVertexColor(c[1], c[2], c[3], cur and 1 or 0.55)
  end
end

