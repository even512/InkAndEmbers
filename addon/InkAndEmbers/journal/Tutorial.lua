function Tutorial.narrator()
  local B, Th = Journal.Begleiter, Journal.Theme
  if not B or type(B.narrator) ~= "function" or not Th or not Th.HAS_NARRATORS or type(Th.narratorTex) ~= "function" then return nil end
  if not state.narrator then
    local ok, id = pcall(B.narrator)
    state.narrator = ok and type(id) == "string" and id or nil
  end
  if not state.narrator then return nil end
  return Th.narratorTex(state.narrator), state.narrator
end

-- Left page: the page's tiles stacked and centred vertically (a lone tile sits in the middle), each with shadow, frame and tape
function Tutorial.layoutImages(p)
  local f = state.frame
  if not f then return end
  local I = Tutorial.IMAGE
  local tex = p.portrait and Tutorial.narrator() or nil
  if tex then f.portrait:SetTexture(tex) end
  f.portrait:SetShown(tex ~= nil)
  local heights, total = {}, 0
  for k, tile in ipairs(p.tiles) do
    heights[k] = floor(I.w * tile.h / tile.w + 0.5)
    total = total + heights[k] + (k > 1 and I.gap or 0)
  end
  local y = I.top + floor(max(0, (I.bottom - I.top - total) / 2))
  for slot, sh in ipairs(f.images) do
    local tile = p.tiles[slot]
    for _, part in ipairs({ sh.shadow, sh.line, sh.tex, sh.tape }) do part:SetShown(tile ~= nil) end
    if tile then
      local h = heights[slot]
      sh.shadow:ClearAllPoints()
      sh.shadow:SetPoint("TOPLEFT", f.left, "TOPLEFT", I.x + 3, -(y + 4))
      sh.shadow:SetSize(I.w, h)
      sh.line:ClearAllPoints()
      sh.line:SetPoint("TOPLEFT", f.left, "TOPLEFT", I.x - 1, -(y - 1))
      sh.line:SetSize(I.w + 2, h + 2)
      sh.tex:ClearAllPoints()
      sh.tex:SetPoint("TOPLEFT", f.left, "TOPLEFT", I.x, -y)
      sh.tex:SetSize(I.w, h)
      sh.tex:SetTexture(Tutorial.texture(tile.a))
      sh.tex:SetTexCoord(Tutorial.tileCoords(tile))
      y = y + h + I.gap
    end
  end
end

-- Right page text: the largest font size whose wrapped height fits the page (the texts differ a lot in length)
function Tutorial.fitBody(text)
  local f = state.frame
  if not f then return end
  local Th = Theme()
  local file = (Th.FONT and Th.FONT.text) or "Fonts\\FRIZQT__.TTF"
  local size
  for _, s in ipairs(Tutorial.BODY_SIZES) do
    size = s
    pcall(f.body.SetFont, f.body, file, s, "")
    setText(f.body, text)
    local h = f.body.GetStringHeight and f.body:GetStringHeight()
    if type(h) ~= "number" or isSecret(h) or h <= Tutorial.BODY_MAX then break end
  end
  return size
end

local function render()
  local f = state.frame
  if not f then return end
  local n = #Tutorial.pages()
  local i = state.page
  local p = Tutorial.pages()[i]
  setText(f.headL, f.upper(T.header))
  setText(f.headR, f.upper(T("pageOf", i, n)))
  setText(f.title, T["title_" .. p.id])
  Tutorial.fitBody(T[Tutorial.textKey(p)])
  Tutorial.layoutImages(p)
  local last = i == n
  if f.next.SetLabel then f.next:SetLabel(last and T.done or T.next) end
  if f.back.SetLabel then f.back:SetLabel(T.back) end
  f.back:SetShown(i > 1)
  f.skip:SetLabel(T.skip)
  f.skip:SetShown(not last)
  Tutorial.paintDots()
end
Tutorial.render = render

function Tutorial.isShown()
  return state.frame ~= nil and state.frame:IsShown() and true or false
end

function Tutorial.page() return state.page end

function Tutorial.open(i)
  if inCombat() then
    print_(T.combat)
    return false
  end
  local f = build()
  local n = #Tutorial.pages()
  if not f:IsShown() then state.narrator = nil end
  i = tonumber(i) or 1
  state.page = max(1, min(n, floor(i)))
  render()
  if not f:IsShown() then
    f:Show()
    play("open")
  end
  return true
end

function Tutorial.go(i)
  if not Tutorial.isShown() then return false end
  local n = #Tutorial.pages()
  i = tonumber(i)
  if not i then return false end
  i = max(1, min(n, floor(i)))
  if i == state.page then return true end
  state.page = i
  render()
  play("page")
  return true
end

function Tutorial.next()
  if not Tutorial.isShown() then return false end
  if state.page >= #Tutorial.pages() then
    Tutorial.close()
    return true
  end
  return Tutorial.go(state.page + 1)
end

function Tutorial.prev()
  if not Tutorial.isShown() or state.page <= 1 then return false end
  return Tutorial.go(state.page - 1)
end

function Tutorial.close()
  if state.frame and state.frame:IsShown() then
    state.frame:Hide()
  end
end

function Tutorial.onHidden()
  state.narrator = nil
  play("close")
  local list = state.after
  state.after = {}
  for _, fn in ipairs(list) do
    local ok, err = pcall(fn)
    if not ok and ns.Core and ns.Core.coreError then ns.Core.coreError(err) end
  end
end

function Tutorial.firstRun(after)
  if not Tutorial.AUTO or Tutorial.seen() then return false end
  if not Tutorial.open(1) then return false end
  Tutorial.setSeen(true)
  if type(after) == "function" then state.after[#state.after + 1] = after end
  return true
end

function Tutorial.slash()
  return Tutorial.open(1)
end
