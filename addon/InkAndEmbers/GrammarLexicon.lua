-- Lexicon of place names for Grammar.lua: article class per client name, German (deDE) and English (enUS).
-- Hand-written from the map names of journal/MapSpace.lua (uiMapID -> deDE/enUS, Retail and WoW Forever), the zone list of
-- InkAndEmbers_Data/Zones.lua (QuestieDB/Forever names, partly English in the German client) and the dungeon list of
-- InkAndEmbers_QuestData/Dungeons.lua, plus capitals and frequent towns. Names stay exactly as the client writes them
-- (with "Das"/"Die"/"The" where the client has it); the class belongs to the name without that article.
-- Row: E({ uiMapID, ... }, { deName, class, ... }, { enName, class, ... }); the first pair of a language is the class used
-- for a uiMapID whose name is not listed.
-- German classes: "-" no article (in Westfall), "m" | "f" | "n" | "pl"; a trailing "@" = island ("auf der Insel Zephras").
-- Coasts (head word "-küste") take "an" by themselves (Grammar.lua): "an der Dunkelküste", "zur Dunkelküste".
-- English classes: "-" no article, "the" (in the Barrens); a trailing "@" = island ("on the Darkspear Islands").
local _, ns = ...

local rows = {}
ns.GrammarLexicon = rows

local function E(ids, de, en)
  rows[#rows + 1] = { ids = ids, de = de, en = en }
end

