  if state.frame then return state.frame end
  local Th = Theme()
  local Fr = Journal.Frame
  local f = CreateFrame("Frame", Tutorial.NAME, UIParent)
  f:SetSize(Tutorial.W, Tutorial.H)
  f:SetPoint("CENTER", UIParent, "CENTER", 0, 30)
  f:SetFrameStrata("FULLSCREEN_DIALOG")
  f:SetToplevel(true)
  f:SetClampedToScreen(true)
  f:EnableMouse(true)
  f:SetMovable(true)
  if f.SetDontSavePosition then f:SetDontSavePosition(true) end
  f:RegisterForDrag("LeftButton")
  f:SetScript("OnDragStart", function(self) self:StartMoving() end)
  f:SetScript("OnDragStop", function(self) self:StopMovingOrSizing() end)
  f:Hide()
  state.frame = f

  local pieces = (Fr and type(Fr.bookPieces) == "function") and Fr.bookPieces(Tutorial.W, Tutorial.H, Tutorial.RIM) or {}
  for _, p in ipairs(pieces) do
    local t = f:CreateTexture(nil, "BACKGROUND", nil, -8)
    t:SetTexture(Th.TEX.book)
    t:SetTexCoord(p.u0, p.u1, p.v0, p.v1)
    t:SetPoint("TOPLEFT", f, "TOPLEFT", p.x, -p.y)
    t:SetSize(p.w, p.h)
  end
  if #pieces == 0 then
    local bg = f:CreateTexture(nil, "BACKGROUND", nil, -8)
    bg:SetAllPoints(f)
    bg:SetColorTexture(0.30, 0.17, 0.10, 1)
  end

  local R = Tutorial.RIM
  local sw, sh = Tutorial.W - 2 * R, Tutorial.H - 2 * R
  local half = sw / 2
  local spread = CreateFrame("Frame", nil, f)
  spread:SetPoint("TOPLEFT", f, "TOPLEFT", R, -R)
  spread:SetSize(sw, sh)
  local pl, pr = "Interface\\AddOns\\InkAndEmbers\\Media\\Page_chronik_L", "Interface\\AddOns\\InkAndEmbers\\Media\\Page_chronik_R"
  if type(Th.paper) == "function" then pl, pr = Th.paper("chronik") end
  local left = CreateFrame("Frame", nil, spread)
  left:SetPoint("TOPLEFT", spread, "TOPLEFT", 0, 0)
  left:SetSize(half, sh)
  local right = CreateFrame("Frame", nil, spread)
  right:SetPoint("TOPLEFT", spread, "TOPLEFT", half, 0)
  right:SetSize(half, sh)
  local paperL = spread:CreateTexture(nil, "BACKGROUND")
  paperL:SetTexture(pl)
  paperL:SetPoint("TOPLEFT", spread, "TOPLEFT", 0, 14)
  paperL:SetSize(half, sh + 18)
  local paperR = spread:CreateTexture(nil, "BACKGROUND")
  paperR:SetTexture(pr)
  paperR:SetPoint("TOPLEFT", spread, "TOPLEFT", half, 14)
  paperR:SetSize(half, sh + 18)
  f.left, f.right = left, right

  local d = D()
  local upper = (d and d.upper) or string.upper
  f.headL = font(left, "label", 11, "sepia")
  f.headL:SetPoint("TOPLEFT", left, "TOPLEFT", 40, -32)
  f.headR = font(right, "label", 11, "sepia")
  f.headR:SetPoint("TOPRIGHT", right, "TOPRIGHT", -40, -32)
  f.headR:SetJustifyH("RIGHT")
  for _, side in ipairs({ left, right }) do
    local line = side:CreateTexture(nil, "ARTWORK")
    line:SetColorTexture(color("faint", 0.9))
    line:SetHeight(1)
    line:SetPoint("TOPLEFT", side, "TOPLEFT", 40, -48)
    line:SetPoint("TOPRIGHT", side, "TOPRIGHT", -40, -48)
  end
  f.upper = upper

  f.images = {}
  for slot = 1, 2 do
    local sh = {}
    sh.shadow = left:CreateTexture(nil, "BORDER")
    sh.shadow:SetColorTexture(0.17, 0.12, 0.07, 0.28)
    sh.line = left:CreateTexture(nil, "ARTWORK", nil, -1)
    sh.line:SetColorTexture(color("sepia", 0.55))
    sh.tex = left:CreateTexture(nil, "ARTWORK")
    if Th.TEX.diaryTape then
      sh.tape = left:CreateTexture(nil, "OVERLAY")
      sh.tape:SetTexture(Th.TEX.diaryTape)
      sh.tape:SetSize(96, 24)
      sh.tape:SetPoint("CENTER", sh.tex, "TOP", 0, 2)
      sh.tape:SetAlpha(0.92)
